#!/usr/bin/env node
// Refresh the Meta Ads MCP tool snapshot from the live server (read-only tools/list; sends the Meta token to Meta).
// Usage: pnpm build && node --env-file=.env bin/meta-mcp-snapshot.js
// Then classify any new tool (and every write's accountParam) in src/modules/ads/meta-mcp/mapping.ts.
import fs from 'node:fs';
import { MetaMcpClient } from '../dist/modules/ads/meta-mcp/client.js';
import { metaMcpSnapshot as previous } from '../dist/modules/ads/meta-mcp/snapshot.js';
import { metaMcpMapping } from '../dist/modules/ads/meta-mcp/mapping.js';

const token = process.env.ADS_DIRECT_META_ACCESS_TOKEN;
if (!token) throw new Error('Set ADS_DIRECT_META_ACCESS_TOKEN (scopes: ads_mcp_management, ads_read, ads_management, catalog_management, business_management, pages_show_list, instagram_basic)');
const client = new MetaMcpClient(async () => token);
let tools;
try { tools = await client.listTools(); } finally { await client.close(); }

const before = new Map(previous.tools.map(t => [t.name, t]));
const after = new Map(tools.map(t => [t.name, t]));
const added = tools.filter(t => !before.has(t.name)).map(t => t.name);
const removed = previous.tools.filter(t => !after.has(t.name)).map(t => t.name);
const changed = tools.filter(t => before.has(t.name) && JSON.stringify(before.get(t.name).inputSchema) !== JSON.stringify(t.inputSchema)).map(t => t.name);
const snapshot = { source: 'live', fetchedAt: new Date().toISOString(), tools };
fs.writeFileSync('src/modules/ads/meta-mcp/snapshot.ts', `// GENERATED by bin/meta-mcp-snapshot.js; do not edit by hand.
// source 'docs' = names/descriptions from Meta's docs with permissive schemas; 'live' = verbatim tools/list.
import type { MetaMcpSnapshot } from './client.js';

export const metaMcpSnapshot: MetaMcpSnapshot = ${JSON.stringify(snapshot, null, 2)};
`);
console.log(JSON.stringify({
  total: tools.length, added, removed, schemaChanged: changed.length,
  unclassified: tools.filter(t => !metaMcpMapping[t.name]).map(t => t.name),
  writesNeedingAccountParam: Object.entries(metaMcpMapping).filter(([name, r]) => r.write && !r.blocked && !r.accountParam && after.has(name)).map(([name]) => name)
}, null, 2));
